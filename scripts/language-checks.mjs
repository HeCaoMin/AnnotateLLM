import assert from 'node:assert/strict';
import path from 'node:path';
export async function runLanguageChecks({page,shadow,until,clickText,fillRich,rpc,manager,context,id,record,artifacts}){
  await page.goto('https://chatgpt.com/c/language-check');
  await until(()=>shadow(r=>!r.querySelector('.fab').hidden),'language page ready');
  await shadow(r=>r.querySelector('.fab').click());await clickText('对话笔记');
  const prose='保存\n\n中文内容 English 한국어';await fillRich(prose,'.sticky-note .rich-text');await clickText('保存');
  await until(async()=>(await rpc({type:'read',cid:'language-check'})).note.body.includes('한국어'),'language note saved');
  const saved=await rpc({type:'read',cid:'language-check'});
  const popup=await context.newPage();await popup.setViewportSize({width:350,height:600});await popup.goto(`chrome-extension://${id}/popup.html`);
  const globe=popup.getByRole('button',{name:'language',exact:true});await globe.waitFor();
  assert.equal(await globe.getAttribute('title'),'language');assert.equal(await globe.locator('svg').count(),1);
  const box=await globe.boundingBox();assert.equal(box.width,box.height);
  const change=async code=>{await globe.click();await popup.locator(`[data-language="${code}"]`).click();};
  await change('en');await popup.getByRole('button',{name:'Pause annotations',exact:true}).waitFor();
  await until(()=>shadow(r=>r.querySelector('.sticky-note h2').textContent==='Conversation note'),'live sticky English');
  assert.equal(await shadow(r=>r.querySelector('.sticky-note .rich-text').textContent),'保存中文内容 English 한국어');
  assert.equal(await shadow(r=>r.querySelector('.sticky-note [data-format=bold]').getAttribute('title')),'Bold');
  await manager.getByRole('button',{name:'Import Markdown',exact:true}).waitFor();
  assert.equal(await manager.locator('html').getAttribute('lang'),'en');
  const privacy=await context.newPage();await privacy.goto(`chrome-extension://${id}/privacy.html`);await privacy.getByRole('heading',{name:'Your data stays in your browser.'}).waitFor();
  assert.equal(/[\u4e00-\u9fff]/u.test(await privacy.locator('body').innerText()),false);
  await globe.click();assert.deepEqual(await popup.getByRole('menuitemradio').allTextContents(),['中文','English','한국어']);
  await popup.screenshot({path:path.join(artifacts,'language-en.png')});await popup.keyboard.press('Escape');
  record('square globe menu selects English globally, including open cards, editor controls, library and privacy');
  const englishExport=await rpc({type:'export',cid:'language-check'});assert.ok(englishExport.startsWith('# AnnotateLLM · Markdown Library'));
  assert.ok((await rpc({type:'previewImport',text:englishExport})).rows.every(row=>row.status==='same'));
  assert.deepEqual(await rpc({type:'read',cid:'language-check'}),saved);
  const allExport=await rpc({type:'export'});
  await manager.locator('input[type=file]').setInputFiles({name:'language.md',mimeType:'text/markdown',buffer:Buffer.from(allExport)});
  await manager.getByRole('dialog',{name:'Import preview',exact:true}).waitFor();
  await manager.locator('.import-modal details').evaluateAll(items=>items.forEach(item=>item.open=true));
  await manager.getByText('Source:',{exact:true}).first().waitFor();
  assert.ok((await manager.locator('.import-modal pre').allTextContents()).includes(prose));
  record('localized export reimports without data changes; user notes remain verbatim');
  await change('ko');await popup.getByRole('button',{name:'주석 기능 일시 중지',exact:true}).waitFor();
  await until(()=>shadow(r=>r.querySelector('.sticky-note h2').textContent==='대화 노트'),'live sticky Korean');
  await manager.getByRole('button',{name:'Markdown 가져오기',exact:true}).waitFor();await privacy.getByRole('heading',{name:'데이터는 브라우저에 보관됩니다.'}).waitFor();
  await manager.getByRole('dialog',{name:'가져오기 미리보기',exact:true}).waitFor();
  await manager.getByText('원문:',{exact:true}).first().waitFor();
  assert.ok((await manager.locator('.import-modal pre').allTextContents()).includes(prose));
  await manager.getByRole('button',{name:'취소',exact:true}).click();
  assert.equal(await shadow(r=>r.querySelector('.sticky-note [data-format=bold]').getAttribute('title')),'굵게');
  await popup.screenshot({path:path.join(artifacts,'language-ko.png')});
  await popup.reload();await popup.getByRole('button',{name:'주석 기능 일시 중지',exact:true}).waitFor();
  await page.reload();await until(()=>shadow(r=>r.querySelector('.sticky-note h2')?.textContent==='대화 노트'),'language persists on reload');
  record('Korean applies live across open surfaces and survives popup and conversation reloads');
  // A dirty draft must survive a language switch without replacing the editor.
  await shadow(r=>r.querySelector('.sticky-note .rich-text').focus());await page.keyboard.press('Control+End');await page.keyboard.type(' draft');
  await change('zh');await until(()=>shadow(r=>r.querySelector('.sticky-note h2').textContent==='对话笔记'),'back to Chinese');
  assert.ok(await shadow(r=>r.querySelector('.sticky-note .rich-text').textContent.includes('한국어 draft')));
  await popup.getByRole('button',{name:'暂停批注功能',exact:true}).waitFor();
  await clickText('保存');await until(()=>shadow(r=>r.querySelector('.sticky-note [role=status]').textContent==='已保存'),'draft saved after switch');
  await manager.getByRole('button',{name:'导入 Markdown',exact:true}).waitFor();
  await popup.close();await privacy.close();record('switching back to Chinese preserves the active draft and restores labels');
}
